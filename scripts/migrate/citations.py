#!/usr/bin/env python3
"""Convert MkDocs-style citations to Hugo shortcodes.

The migrated corpus used MkDocs ``pymdownx.snippets``-style citation markers:

* ``[@key]``               -> ``{{< cite "key" >}}``
* ``[@a; @b]``             -> ``{{< cite "a" >}}; {{< cite "b" >}}``
* ``[@a][@b]`` (adjacent)  -> ``{{< cite "a" >}}; {{< cite "b" >}}``
* a standalone ``\\full_bibliography`` line -> ``{{< bibliography >}}``

Only keys present in the refs JSON (``data/refs.json``, generated by
``scripts/bib_to_json.py``) are converted; unknown keys are left untouched so
that ``--check`` can report them.  This deliberately guards the Javadoc-style
``[@author ...]`` / ``[@version ...]`` tags in ``devel/library/rpc/index.md``.

Protected regions: fenced code blocks (``` and ~~~, any fence length), inline
code spans (any backtick run length) and YAML/TOML front matter are never
touched.

Usage:
    python3 citations.py [CONTENT_ROOT] [REFS_JSON]
                         [--dry-run | --check] [--exclude PATH]...

``CONTENT_ROOT`` defaults to ``content``, ``REFS_JSON`` to ``data/refs.json``.
``--dry-run`` prints what would change without writing.  ``--check`` writes
nothing and reports every remaining citation-like ``[@...]``, leftover
``\\full_bibliography`` marker and ``cite`` shortcode with an unknown key.

Exit codes: 0 on success, 1 on I/O or usage error, 2 when ``--check`` finds
problems.  Running the script twice is a no-op the second time.
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import sys

CITE_TEMPLATE = '{{< cite "%s" >}}'
BIBLIOGRAPHY_MARKER = r"\full_bibliography"
BIBLIOGRAPHY_SHORTCODE = "{{< bibliography >}}"

# A citation key: no whitespace, no brackets, no ';'.
KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.:+/@-]*$")

# ``[@content]`` on a single line, without crossing other brackets.
GROUP_RE = re.compile(r"\[(@[^\[\]\n]*)\]")

# Javadoc tags: not citations.
JAVADOC_TAGS = {
    "author", "version", "since", "param", "return", "returns", "throws",
    "exception", "see", "deprecated", "serial", "serialfield", "serialdata",
    "inheritdoc", "link", "linkplain", "code", "literal", "value", "docroot",
    "summary", "hidden", "provides", "uses", "apinote", "implspec",
    "implnote", "systemproperty", "index",
}

FENCE_OPEN_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
BIB_MARKER_RE = re.compile(r"^(\s*)" + re.escape(BIBLIOGRAPHY_MARKER) + r"\s*$")
CITE_SHORTCODE_RE = re.compile(r'\{\{[<%]\s*cite\s+"([^"]+)"\s*[>%]\}\}')


# --------------------------------------------------------------------------
# protected regions
# --------------------------------------------------------------------------

def split_inline_code(line):
    """Split a line into ``(is_code, text)`` chunks at backtick spans."""
    chunks = []
    buf = []
    i = 0
    n = len(line)
    while i < n:
        if line[i] != "`":
            buf.append(line[i])
            i += 1
            continue
        j = i
        while j < n and line[j] == "`":
            j += 1
        ticks = line[i:j]
        close = line.find(ticks, j)
        if close < 0:  # unmatched backticks: treat literally
            buf.append(ticks)
            i = j
            continue
        if buf:
            chunks.append((False, "".join(buf)))
            buf = []
        chunks.append((True, line[i:close + len(ticks)]))
        i = close + len(ticks)
    if buf:
        chunks.append((False, "".join(buf)))
    return chunks


def _closing_fence(line, fence):
    char, length = fence
    return re.match(r"^ {0,3}(" + re.escape(char) + r"{%d,})\s*$" % length,
                    line) is not None


def _front_matter_end(lines):
    """Index of the last line of leading YAML/TOML front matter, or -1."""
    if lines and lines[0].strip() in ("---", "+++"):
        delim = lines[0].strip()
        for i in range(1, len(lines)):
            if lines[i].strip() == delim:
                return i
    return -1


# --------------------------------------------------------------------------
# conversion
# --------------------------------------------------------------------------

def _is_javadoc(key):
    parts = key.split()
    return bool(parts) and parts[0].lower() in JAVADOC_TAGS


def convert_group(content, keys, used_keys=None):
    """Convert one ``[@...]`` group; ``None`` means leave it unchanged."""
    if ";" in content:
        parts = [part.strip() for part in content.split(";")]
        if not all(part.startswith("@") for part in parts):
            return None
        cited = [part[1:].strip() for part in parts]
        if not all(KEY_RE.match(cite) for cite in cited):
            return None
        if not all(cite in keys for cite in cited):
            return None
        if used_keys is not None:
            used_keys.update(cited)
        return "; ".join(CITE_TEMPLATE % cite for cite in cited), len(cited)

    text = content.strip()
    if not text.startswith("@"):
        return None
    key = text[1:].strip()
    if not KEY_RE.match(key) or _is_javadoc(key):
        return None
    if key not in keys:
        return None
    if used_keys is not None:
        used_keys.add(key)
    return CITE_TEMPLATE % key, 1


def convert_segment(segment, keys, used_keys=None):
    """Convert all citation groups in a code-free segment."""
    count = 0

    def replace(match):
        nonlocal count
        converted = convert_group(match.group(1), keys, used_keys)
        if converted is None:
            return match.group(0)
        count += converted[1]
        return converted[0]

    converted = GROUP_RE.sub(replace, segment)
    # "[@a][@b]" became "{{< cite "a" >}}{{< cite "b" >}}": add a separator.
    return converted.replace('>}}{{< cite "', '>}}; {{< cite "'), count


def convert_line(line, keys, used_keys=None):
    """Convert one line; return ``(new_line, citation_count, marker_count)``."""
    marker = BIB_MARKER_RE.match(line)
    # A marker indented by four or more spaces is an indented code block.
    if marker and len(marker.group(1)) <= 3:
        return marker.group(1) + BIBLIOGRAPHY_SHORTCODE, 0, 1

    pieces = []
    citations = 0
    for is_code, chunk in split_inline_code(line):
        if is_code:
            pieces.append(chunk)
            continue
        converted, count = convert_segment(chunk, keys, used_keys)
        pieces.append(converted)
        citations += count
    return "".join(pieces), citations, 0


def convert_text(text, keys, used_keys=None):
    """Convert a whole file; return ``(new_text, citations, markers)``."""
    lines = text.splitlines(keepends=True)
    front_end = _front_matter_end([line.rstrip("\r\n") for line in lines])
    out = []
    citations = markers = 0
    fence = None
    for index, raw_line in enumerate(lines):
        line = raw_line.rstrip("\r\n")
        eol = raw_line[len(line):]
        if fence is not None:
            out.append(raw_line)
            if _closing_fence(line, fence):
                fence = None
            continue
        opener = FENCE_OPEN_RE.match(line)
        if opener:
            fence = (opener.group(1)[0], len(opener.group(1)))
            out.append(raw_line)
            continue
        if index <= front_end:
            out.append(raw_line)
            continue
        new_line, new_cites, new_markers = convert_line(line, keys, used_keys)
        citations += new_cites
        markers += new_markers
        out.append(new_line + eol)
    return "".join(out), citations, markers


# --------------------------------------------------------------------------
# --check
# --------------------------------------------------------------------------

def find_residuals(text, keys):
    """Return ``[(line_no, message), ...]`` for unconverted citations."""
    problems = []
    lines = text.splitlines()
    front_end = _front_matter_end(lines)
    fence = None
    for index, line in enumerate(lines):
        lineno = index + 1
        if fence is not None:
            if _closing_fence(line, fence):
                fence = None
            continue
        opener = FENCE_OPEN_RE.match(line)
        if opener:
            fence = (opener.group(1)[0], len(opener.group(1)))
            continue
        if index <= front_end:
            continue

        # Only a column-0..3 marker is a residual; 4+ spaces is an indented
        # code sample (same guard as convert_line).
        marker = BIB_MARKER_RE.match(line)
        if marker and len(marker.group(1)) <= 3:
            problems.append((lineno, "unconverted %s" % BIBLIOGRAPHY_MARKER))

        for is_code, chunk in split_inline_code(line):
            if is_code:
                continue
            for match in GROUP_RE.finditer(chunk):
                content = match.group(1)
                if ";" in content:
                    parts = [part.strip() for part in content.split(";")]
                    cited = [part[1:].strip() for part in parts
                             if part.startswith("@")]
                    if len(cited) != len(parts):
                        continue
                else:
                    cited = [content.strip().lstrip("@").strip()]
                if any(_is_javadoc(cite) for cite in cited):
                    continue
                unknown = [cite for cite in cited
                           if KEY_RE.match(cite) and cite not in keys]
                malformed = [cite for cite in cited if not KEY_RE.match(cite)]
                reason = ""
                if unknown:
                    reason = "unknown key " + ", ".join(repr(k) for k in unknown)
                elif malformed:
                    reason = "unrecognised citation"
                elif cited:
                    reason = "not converted"
                if reason:
                    problems.append(
                        (lineno, "remaining citation %s (%s)"
                         % (match.group(0), reason)))

            for match in CITE_SHORTCODE_RE.finditer(chunk):
                if match.group(1) not in keys:
                    problems.append(
                        (lineno, "cite shortcode uses unknown key %r"
                         % match.group(1)))
    return problems


# --------------------------------------------------------------------------
# CLI helpers
# --------------------------------------------------------------------------

def markdown_files(root):
    if os.path.isfile(root):
        yield root
        return
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if name.endswith(".md"):
                yield os.path.join(dirpath, name)


def norm(path):
    path = path.replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    return os.path.normpath(path).replace(os.sep, "/")


def make_excluder(values, root):
    patterns = []
    for value in values or []:
        for part in str(value).split(","):
            part = part.strip()
            if not part:
                continue
            if os.path.isabs(part):
                part = os.path.relpath(part, root)
            for prefix in (root + os.sep, "content" + os.sep, "./"):
                if part.startswith(prefix):
                    part = part[len(prefix):]
            patterns.append(norm(part))
    return patterns


def is_excluded(rel, patterns):
    rel = norm(rel)
    for pattern in patterns:
        if fnmatch.fnmatch(rel, pattern):
            return True
        if rel == pattern or rel.startswith(pattern.rstrip("/") + "/"):
            return True
    return False


def load_refs(path):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except OSError as exc:
        raise SystemExit("error: cannot read %s: %s" % (path, exc))
    except json.JSONDecodeError as exc:
        raise SystemExit("error: %s is not valid JSON: %s" % (path, exc))
    if not isinstance(data, dict):
        raise SystemExit("error: %s must contain a JSON object" % path)
    return set(data)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("root", nargs="?", default="content",
                        help="content root or single .md file (default: content)")
    parser.add_argument("refs", nargs="?", default="data/refs.json",
                        help="refs JSON (default: data/refs.json)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true",
                      help="report changes without writing files")
    mode.add_argument("--check", action="store_true",
                      help="fail (exit 2) if any citation remains")
    parser.add_argument("--exclude", action="append", default=[],
                        metavar="PATH",
                        help="skip this file or directory (repeatable)")
    args = parser.parse_args(argv)

    if not os.path.exists(args.root):
        print("error: %s does not exist" % args.root, file=sys.stderr)
        return 1
    try:
        keys = load_refs(args.refs)
    except SystemExit as exc:
        print(exc, file=sys.stderr)
        return 1

    root = args.root.rstrip("/") or args.root
    excluded = make_excluder(args.exclude, root)
    files = [path for path in markdown_files(root)
             if not is_excluded(os.path.relpath(path, root)
                                if os.path.isdir(root) else os.path.basename(path),
                                excluded)]
    if not files:
        print("error: no markdown files under %s" % args.root, file=sys.stderr)
        return 1

    if args.check:
        failures = []
        for path in files:
            with open(path, "r", encoding="utf-8") as handle:
                text = handle.read()
            rel = os.path.relpath(path, root) if os.path.isdir(root) else path
            for lineno, message in find_residuals(text, keys):
                failures.append((norm(rel), lineno, message))
        for rel, lineno, message in failures:
            print("%s:%d: %s" % (rel, lineno, message))
        print("citations --check: %d file(s) scanned, %d failure(s), "
              "%d known key(s)" % (len(files), len(failures), len(keys)))
        return 2 if failures else 0

    scanned = changed = citations = markers = 0
    used_keys = set()
    for path in files:
        scanned += 1
        with open(path, "r", encoding="utf-8", newline="") as handle:
            text = handle.read()
        new_text, new_cites, new_markers = convert_text(text, keys, used_keys)
        if new_text == text:
            continue
        changed += 1
        citations += new_cites
        markers += new_markers
        rel = os.path.relpath(path, root) if os.path.isdir(root) else path
        rel = norm(rel)
        if args.dry_run:
            print("would convert %s (%d citation(s), %d bibliography marker(s))"
                  % (rel, new_cites, new_markers))
        else:
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(new_text)
            print("converted %s (%d citation(s), %d bibliography marker(s))"
                  % (rel, new_cites, new_markers))

    verb = "would convert" if args.dry_run else "converted"
    print("citations: %d file(s) scanned, %d %s, %d citation(s), "
          "%d bibliography marker(s), %d distinct key(s) used"
          % (scanned, changed, verb, citations, markers, len(used_keys)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
